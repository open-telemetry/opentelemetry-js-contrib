// Emits compatibility stubs at the file paths that the pre-tsdown layout
// published, each one re-exporting the current `dist/` target. Run from a
// package directory, after `tsdown`.
//
// Those paths were always an implementation detail, and ordinary consumers
// never needed them: a bare specifier goes through the `exports` map. Process
// level injectors cannot. Node applies conditional exports only to bare
// specifiers, so `--require /abs/path/node_modules/@opentelemetry/
// auto-instrumentations-node/register` does not resolve, and every injector
// therefore hardcodes the internal file path instead. Those hardcoded paths
// live in configuration files on machines that are already provisioned, which
// a package upgrade cannot rewrite -- so dropping `build/src/register.js`
// stops instrumentation on those hosts, silently, at the next upgrade.
//
// This is a migration ramp, not a reinstated contract. It can be deleted once
// the Node.js injection contract is specified and injectors have a supported
// path to target: https://github.com/open-telemetry/opentelemetry-injector/issues/451

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

// Package name -> { path published before the tsdown migration: current target }.
// Both are relative to the package root. Only paths with a known injector
// consumer belong here; `build/src/index.js` is deliberately absent, because
// reaching the package root works through the `main` field at any file path.
const LEGACY_ENTRYPOINTS = {
  '@opentelemetry/auto-instrumentations-node': {
    'build/src/register.js': 'dist/register.cjs',
  },
};

const pkgDir = process.cwd();
const pkg = JSON.parse(readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
const stubs = LEGACY_ENTRYPOINTS[pkg.name];

if (!stubs) {
  console.error(
    `legacy-entrypoints: ${pkg.name} declares no legacy entrypoints; ` +
      'remove this step from its compile script.'
  );
  process.exit(1);
}

for (const [legacy, target] of Object.entries(stubs)) {
  const file = path.join(pkgDir, legacy);
  // A require specifier is POSIX-shaped on every platform, and needs the
  // leading `./` that `path.relative` only omits when it already starts `../`.
  const rel = path
    .relative(path.dirname(file), path.join(pkgDir, target))
    .split(path.sep)
    .join('/');
  const specifier = rel.startsWith('.') ? rel : `./${rel}`;

  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(
    file,
    `/*
 * Copyright The OpenTelemetry Authors
 * SPDX-License-Identifier: Apache-2.0
 */

// Generated by scripts/legacy-entrypoints.mjs -- do not edit.
//
// Compatibility stub for the build layout published before 0.82.0, kept so
// that injectors holding this path in their configuration keep working.
// Use the documented entrypoint instead: '${pkg.name}/register'.

module.exports = require('${specifier}');
`
  );
  console.log(`legacy-entrypoints: ${pkg.name} ${legacy} -> ${target}`);
}
