/**
 * Options for starting an inference invocation.
 */
export interface InferenceInvocationOptions {
  /** Name of the provider (e.g. 'openai', 'anthropic', 'aws.bedrock'). */
  providerName: string;
  /** Operation name (e.g. 'chat', 'text_completion', 'generate_content'). Defaults to 'chat'. */
  operationName?: string;
  /** Model name requested (`gen_ai.request.model`). */
  requestModel?: string;
  /** Custom initial span attributes. */
  attributes?: Attributes;
  /** Server address (e.g. hostname). */
  serverAddress?: string;
  /** Server port. */
  serverPort?: number;
}

/**
 * Options for starting an embedding invocation.
 */
export interface EmbeddingInvocationOptions {
  /** Name of the provider (`gen_ai.provider.name`). */
  providerName: string;
  /** Model name requested (`gen_ai.request.model`). */
  requestModel?: string;
  /** Server address. */
  serverAddress?: string;
  /** Server port. */
  serverPort?: number;
  /** Custom initial span attributes. */
  attributes?: Attributes;
}

/**
 * Options for starting a tool execution invocation.
 */
export interface ToolInvocationOptions {
  /** Name of the tool being executed (`gen_ai.tool.name`). */
  toolName: string;
  /** Type classification of the tool (`gen_ai.tool.type`). */
  toolType?: ToolType;
  /** Parent context. */
  parentContext?: Context;
  /** Human-readable name of the agent executing the tool (`gen_ai.agent.name`). */
  agentName?: string;
  /** Custom initial span attributes. */
  attributes?: Attributes;
}

// ============================================================================
// Hook and Result Types
// ============================================================================

/**
 * Summary result passed to CompletionHook upon invocation finish.
 */
export interface CompletionResult {
  /** The OpenTelemetry span for this invocation. */
  span: Span;
  /** Provider name (`gen_ai.provider.name`). */
  providerName?: string;
  /** Operation name (`gen_ai.operation.name`). */
  operationName?: string;
  /** Requested model name (`gen_ai.request.model`). */
  requestModel?: string;
  /** Response model name (`gen_ai.response.model`). */
  responseModel?: string;
  /** Response ID (`gen_ai.response.id`). */
  responseId?: string;
  /** Lifecycle response status (`gen_ai.response.status`). */
  responseStatus?: ResponseStatus;
  /** Finish reasons (`gen_ai.response.finish_reasons`). */
  finishReasons?: string[];
  /** Token usage. */
  usage?: TokenUsage;
  /** Duration of the operation in seconds. */
  durationSeconds?: number;
  /** Input messages if captured (`gen_ai.input.messages`). */
  inputMessages?: InputMessages;
  /** Output messages if captured (`gen_ai.output.messages`). */
  outputMessages?: OutputMessages;
  /** System instructions if captured (`gen_ai.system_instructions`). */
  systemInstructions?: SystemInstructions;
  /** Error if the invocation failed. */
  error?: Error;
  /** Custom attributes. */
  attributes?: Attributes;
}

/**
 * Hook executed when a GenAI operation finishes (success or failure).
 */
export interface CompletionHook {
  /**
   * Callback invoked when a GenAI operation completes.
   * If an exception is thrown, it will be safely caught and logged without affecting user flow.
   */
  onCompletion(result: CompletionResult): void | Promise<void>;
}

/**
 * Base configuration interface for GenAI instrumentations.
 */
export interface GenAIInstrumentationConfig {
  /**
   * Controls capturing of prompt, completion, and tool call contents.
   * - `'none'`: no content captured (default).
   * - `'span_only'`: content captured on span attributes.
   */
  captureMessageContent?: ContentCaptureMode;

  /**
   * Optional custom completion hooks.
   */
  completionHooks?: CompletionHook[];
}
